# Differences introduced by D-15 rounding on the frozen slates (pinned, explained in
# docs/weekly_challenge_engine.md): no recovery decision changes and no
# recommendation changes; expected returns move by < 0.01 credit, which re-orders a
# few near-tied groupings (expected returns within fractions of a cent) on the
# expected-return axis and flips their efficiency.
D15_EFFICIENCY_FLIPS = {
    "S08": {"025|168|347", "047|135|268", "048|135|267", "067|135|248"},
    "S11": {"035|168|247", "036|158|247"},
    "S13": {"037|128|456", "047|123|568"},
}


@pytest.mark.parametrize("slate", REG["slates"], ids=lambda s: s["name"][:3])
def test_phase5b_regression_settlement_convention(slate):
    exact = evaluate_all(slate_sels(slate), Precision.EXACT)
    settle = evaluate_all(slate_sels(slate))
    for a, b in zip(exact.results, settle.results, strict=True):
        assert a.p_recover == b.p_recover  # no recovery decision changed by rounding
        for x, y in zip(a.states, b.states, strict=True):  # ...state by state
            assert (x.gross >= pf.RECOVERY_TARGET) == (y.gross >= pf.RECOVERY_TARGET)
        assert abs(a.expected_gross - b.expected_gross) < 0.01
        for x, y in zip(a.buckets, b.buckets, strict=True):
            assert y.payout == round_credits(x.payout)
            assert abs(x.payout - y.payout) <= D("0.005")
    flips = {a.partition_id for a, b in zip(exact.results, settle.results, strict=True)
             if a.efficient != b.efficient}  # fmt: skip
    assert flips == D15_EFFICIENCY_FLIPS.get(slate["name"][:3], set())
    assert settle.recommended_id == exact.recommended_id == slate["recommended"]


