def test_bucket_odds_probabilities_and_payouts():
    r = evaluate_partition(MIXED, "012|345|678")
    a, b, c = r.buckets
    assert a.combined_odds == D("1.70") * D("1.90") * D("2.10") == D("6.783")
    assert a.win_probability == pytest.approx(0.6 * 0.55 * 0.5, rel=1e-15)
    assert a.stake == b.stake == c.stake == 30 and r.nine_fold.stake == 10
    assert a.payout == round_credits(30 * D("6.783")) == D("203.49")
    nine_odds = math.prod((s.odds for s in MIXED), start=D(1))
    assert r.nine_fold.combined_odds == nine_odds
    assert r.nine_fold.payout == round_credits(10 * nine_odds)
    assert r.nine_fold.win_probability == pytest.approx(math.prod(s.probability for s in MIXED))
    assert pf.TOTAL_STAKE == 100 and pf.ALLOCATION_VERSION == "30-30-30-10/v1"


def test_eight_states_probabilities_and_nine_fold_dependency():
    r = evaluate_partition(MIXED, "036|147|258")
    assert [s.wins for s in r.states] == list(itertools.product((0, 1), repeat=3))
    assert sum(s.probability for s in r.states) == pytest.approx(1.0, abs=1e-15)
    P = [b.win_probability for b in r.buckets]
    for s in r.states:
        expect = math.prod(P[j] if s.wins[j] else 1 - P[j] for j in range(3))
        assert s.probability == pytest.approx(expect, rel=1e-15)
        bucket_sum = sum((r.buckets[j].payout for j in range(3) if s.wins[j]), D(0))
        if all(s.wins):  # nine-fold only when all three buckets win
            assert s.gross == bucket_sum + r.nine_fold.payout == r.max_gross
        else:
            assert s.gross == bucket_sum
    assert r.states[-1].probability == pytest.approx(r.nine_fold.win_probability, rel=1e-12)
    assert r.states[0].gross == 0 and r.p_zero == pytest.approx(math.prod(1 - p for p in P))


def test_matches_exact_rational_reference():
    rnd = random.Random(7)
    for _ in range(25):
        ps = [Fraction(rnd.randint(5, 95), 100) for _ in range(9)]
        os_ = [Fraction(rnd.randint(101, 900), 100) for _ in range(9)]
        part = pf.partitions()[rnd.randrange(280)]
        sels = sels_from([float(p) for p in ps], [D(o.numerator) / o.denominator for o in os_])
        r = evaluate_partition(sels, part, Precision.EXACT)
        P = [math.prod((ps[i] for i in g), start=Fraction(1)) for g in part]
        O = [math.prod((os_[i] for i in g), start=Fraction(1)) for g in part]  # noqa: E741
        O9 = math.prod(os_, start=Fraction(1))
        mean = rec = Fraction(0)
        for wins in itertools.product((0, 1), repeat=3):
            pr = math.prod((P[j] if wins[j] else 1 - P[j] for j in range(3)), start=Fraction(1))
            gross = sum((30 * O[j] for j in range(3) if wins[j]), Fraction(0))
            gross += 10 * O9 if all(wins) else 0
            mean += pr * gross
            rec += pr if gross >= 100 else 0
        assert r.expected_gross == pytest.approx(float(mean), rel=1e-12)
        assert r.p_recover == pytest.approx(float(rec), abs=1e-12)


