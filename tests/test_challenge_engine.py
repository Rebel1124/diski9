def test_half_up_rounding_to_one_credit_cent():
    cases = {"0.005": "0.01", "0.015": "0.02", "2.675": "2.68", "99.995": "100.00",
             "99.9949": "99.99", "116.5788": "116.58", "100.696380": "100.70"}  # fmt: skip
