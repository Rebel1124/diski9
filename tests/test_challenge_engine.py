def _edge(odds_a, odds_b, p=0.5):
    """Bucket A = selections 0-2 with odds (odds_a, 1, 1); B likewise with odds_b."""
    odds = [odds_a, "1.00", "1.00", odds_b, "1.00", "1.00", "1.01", "1.01", "1.01"]
    return sels_from([p] * 9, odds)


def test_threshold_edge_cases_near_100_credits():
    # 30 x 3.3332 = 99.996 -> settles at 100.00: recovers under D-15, not when unrounded
    s = _edge("3.3332", "1.10")
    st = evaluate_partition(s, "012|345|678")
    ex = evaluate_partition(s, "012|345|678", Precision.EXACT)
    assert st.buckets[0].payout == D("100.00") and st.buckets[0].recovers_alone
    assert ex.buckets[0].payout == D("99.996") and not ex.buckets[0].recovers_alone
    assert st.p_recover > ex.p_recover
    # 30 x 3.33313 = 99.9939 -> 99.99: does not recover under either convention
    s = _edge("3.33313", "1.10")
    assert not evaluate_partition(s, "012|345|678").buckets[0].recovers_alone
    # exactly 100.00 recovers (>= is inclusive)
    s = _edge("3.33334", "1.10")  # 30 x 3.33334 = 100.0002 -> 100.00
    assert evaluate_partition(s, "012|345|678").buckets[0].payout == D("100.00")
    # two accumulators each rounding up: 50.00505 -> 50.01 and 49.992 -> 49.99
    s = _edge("1.666835", "1.6664")
    st = evaluate_partition(s, "012|345|678")
    ex = evaluate_partition(s, "012|345|678", Precision.EXACT)
    a_b = next(x for x in st.states if x.wins == (1, 1, 0))
    assert a_b.gross == D("100.00")  # recovers under D-15
    assert next(x for x in ex.states if x.wins == (1, 1, 0)).gross < 100  # 99.99705 unrounded


