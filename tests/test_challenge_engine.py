def _brute_force(points):
    snapped = [(round(x / pf.PROB_GRID), round(y / pf.CREDIT_GRID)) for x, y in points]
    return [
        not any(q[0] >= p[0] and q[1] >= p[1] and (q[0] > p[0] or q[1] > p[1]) for q in snapped)
        for p in snapped
    ]


@pytest.mark.parametrize("seed", range(10))
def test_pareto_sweep_matches_brute_force(seed):
    rnd = random.Random(seed)
    pts = [
        (rnd.choice([0.1, 0.2, 0.3, 0.3]), rnd.choice([50.0, 60.0, 60.0, 70.0])) for _ in range(60)
    ]  # fmt: skip — many ties on both axes
    pts += [(rnd.random(), rnd.random() * 100) for _ in range(60)]
    assert pf.efficient_mask(pts) == _brute_force(pts)
    perm = list(range(len(pts)))
    rnd.shuffle(perm)
    shuffled = pf.efficient_mask([pts[i] for i in perm])
    assert shuffled == [pf.efficient_mask(pts)[i] for i in perm]  # order-independent


def test_pareto_ties_and_tolerance():
    assert pf.efficient_mask([(0.5, 10), (0.4, 20), (0.5, 10), (0.3, 5), (0.5, 9)]) == [
        True, True, True, False, False]  # fmt: skip
    # floating-point noise below the grids counts as equal: both efficient
    assert pf.efficient_mask([(0.5, 10.0), (0.5 + 1e-15, 10.0 - 1e-7)]) == [True, True]


def test_frontier_classification_and_recommendation_on_real_slates():
    for sl in REG["slates"]:
        ps = evaluate_all(slate_sels(sl))
        pts = [(r.p_recover, r.expected_gross) for r in ps.results]
        assert [r.efficient for r in ps.results] == _brute_force(pts)
        rec = ps.recommended
        assert rec.efficient and rec.recommended
        assert sum(r.recommended for r in ps.results) == 1
        # highest recovery among efficient; ties -> higher expected -> lowest ID
        eff = [r for r in ps.results if r.efficient]
        key = max((round(r.p_recover / pf.PROB_GRID), round(r.expected_gross / pf.CREDIT_GRID))
                  for r in eff)  # fmt: skip
        tied = [r.partition_id for r in eff if (round(r.p_recover / pf.PROB_GRID),
                round(r.expected_gross / pf.CREDIT_GRID)) == key]  # fmt: skip
        assert rec.partition_id == min(tied)


