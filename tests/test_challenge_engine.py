def test_grouping_frontier_invariant_to_selection_order():
    """Partition IDs refer to positions; the *groupings* (sets of selection IDs) that
    are efficient and recommended do not depend on the order selections are given."""

    def groupings(ps):
        out = {}
        for r in ps.results:
            key = frozenset(frozenset(b.selection_ids) for b in r.buckets)
            out[key] = (r.efficient, r.recommended)
        return out

    base = evaluate_all(MIXED)
    perm = MIXED[::-1]
    assert groupings(evaluate_all(perm)) == groupings(base)


