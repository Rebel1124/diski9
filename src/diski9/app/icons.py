ASSET = Path(__file__).parent / "assets" / "icons.css"


def svg(name: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        'stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        f"{ICONS[name]}</svg>"
    )


def css() -> str:
    lines = [
        "/* Generated by `python -m diski9.app.icons` from diski9/app/icons.py.",
        "   Lucide icons (ISC licence, https://lucide.dev), drawn as masks in currentColor. */",
        ".ic { display: inline-block; flex: none; width: 1.05em; height: 1.05em; "
        "vertical-align: -0.16em; background-color: currentColor; -webkit-mask: var(--ic) "
        "center / contain no-repeat; mask: var(--ic) center / contain no-repeat; }",
        ".ic-sm { width: .9em; height: .9em; vertical-align: -0.1em; }",
        ".ic-lg { width: 1.35em; height: 1.35em; vertical-align: -0.28em; }",
    ]
    root = " ".join(f'--ic-{name}: url("data:image/svg+xml,{quote(svg(name))}");' for name in ICONS)
    lines.append(f":root {{ {root} }}")
    for name in ICONS:
        lines.append(f".ic-{name} {{ --ic: var(--ic-{name}); }}")
    return "\n".join(lines) + "\n"


def icon(name: str, extra: str = "") -> html.Span:
    """A decorative icon (``aria-hidden``); pair it with visible text."""
    if name not in ICONS:
        raise KeyError(f"unknown icon {name!r}")
    return html.Span(className=f"ic ic-{name} {extra}".strip(), **{"aria-hidden": "true"})


if __name__ == "__main__":  # pragma: no cover - regenerates the stylesheet
    ASSET.write_text(css())
    print(f"wrote {ASSET}")
